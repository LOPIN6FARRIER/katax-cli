// Requires a recognized transport scheme and rejects a leading "-", which blocks passing
// something like "--upload-pack=..." (a git argument-injection vector) as if it were a repo URL.
const GIT_URL_PATTERN = /^(https?:\/\/|git@|ssh:\/\/|git:\/\/)\S+$/;
const NAME_PATTERN = /^[a-z0-9-_]+$/i;
const CONFIG_FILE = ".katax-deploy.json";
const ECOSYSTEM_FILE = "ecosystem.config.cjs";

export function isValidGitRepoUrl(input: string): boolean {
  return !input.startsWith("-") && GIT_URL_PATTERN.test(input.trim());
}

// ==================== Pure helpers (exported for tests) ====================

export type PackageManager = "pnpm" | "yarn" | "npm";

/** The lockfile decides: projects from `katax init` default to pnpm. */
export function detectPackageManager(dir: string): PackageManager {
  if (fs.existsSync(path.join(dir, "pnpm-lock.yaml"))) return "pnpm";
  if (fs.existsSync(path.join(dir, "yarn.lock"))) return "yarn";
  return "npm";
}

/** Install including devDependencies (TypeScript is needed to build), even if NODE_ENV=production. */
export function installArgs(pm: PackageManager, dir: string): string[] {
  if (pm === "pnpm") return ["install", "--frozen-lockfile", "--prod=false"];
  if (pm === "yarn") return ["install", "--frozen-lockfile", "--production=false"];
  return fs.existsSync(path.join(dir, "package-lock.json")) ? ["ci", "--include=dev"] : ["install", "--include=dev"];
}

/** App name declared in a PM2 ecosystem file (first `name:` entry), without executing it. */
export function readEcosystemAppName(content: string): string | null {
  const match = content.match(/\bname\s*:\s*['"`]([^'"`]+)['"`]/);
  return match?.[1] ?? null;
}

/** Fork + 1 instance: in-memory rate limits, Socket.IO and cron jobs break in cluster mode. */
export function renderDeployEcosystem(appName: string, instances: number, maxMemory: string): string {
  const cluster = instances > 1;
  return `// PM2 config generated by katax deploy (no ecosystem.config.cjs in the repo).
// ${cluster ? "Cluster mode: rate limits, Socket.IO and cron need Redis/sticky sessions to work across instances." : "One instance in fork mode: in-memory rate limits, Socket.IO and cron need it."}
module.exports = {
  apps: [
    {
      name: '${appName}',
      script: 'dist/index.js',
      instances: ${instances},
      exec_mode: '${cluster ? "cluster" : "fork"}',
      max_memory_restart: '${maxMemory}',
      out_file: './logs/pm2-out.log',
      error_file: './logs/pm2-error.log',
      merge_logs: true,
      log_date_format: 'YYYY-MM-DD HH:mm:ss Z',
      min_uptime: '10s',
      max_restarts: 10,
      env: { NODE_ENV: 'production' }
    }
  ]
};
`;
}

export interface EnvEntry {
  key: string;
  value: string;
}

/** KEY=value lines of a .env.example (comments and blank lines ignored). */
export function parseEnvFile(content: string): EnvEntry[] {
  const entries: EnvEntry[] = [];
  for (const raw of content.split(/\r?\n/)) {
    const line = raw.trim();
    if (!line || line.startsWith("#")) continue;
    const eq = line.indexOf("=");
    if (eq <= 0) continue;
    const key = line.slice(0, eq).trim();
    if (!/^[A-Z_][A-Z0-9_]*$/i.test(key)) continue;
    entries.push({ key, value: line.slice(eq + 1).trim().replace(/^(['"])(.*)\1$/, "$2") });
  }
  return entries;
}

export function isSecretKey(key: string): boolean {
  return /SECRET|PASSWORD|TOKEN|PRIVATE|API_KEY/i.test(key);
}

/** Default for each .env key on a server: production mode and fresh random secrets. */
export function productionDefault(entry: EnvEntry): string {
  if (entry.key === "NODE_ENV") return "production";
  if (/SECRET/i.test(entry.key) && (entry.value === "" || /change[-_]?me/i.test(entry.value))) {
    return crypto.randomBytes(64).toString("hex");
  }
  return entry.value;
}

export function renderEnvFile(entries: EnvEntry[]): string {
  return `# Generated by katax deploy\n${entries.map((e) => `${e.key}=${e.value}`).join("\n")}\n`;
}

function normalizeDir(dir: string): string {
  const resolved = path.resolve(dir);
  return process.platform === "win32" ? resolved.toLowerCase() : resolved;
}

interface Pm2Process {
  name?: string;
  pm2_env?: { pm_cwd?: string; pm_exec_path?: string };
}

/**
 * PM2 app running from exactly this directory (its cwd, or a script in it or in dist/).
 * Exact matches only: a prefix match picked /apps/api-v2 when updating /apps/api.
 */
export function findPm2AppForDir(processes: Pm2Process[], dir: string): string | null {
  const target = normalizeDir(dir);
  for (const proc of processes) {
    if (proc.name && proc.pm2_env?.pm_cwd && normalizeDir(proc.pm2_env.pm_cwd) === target) return proc.name;
  }
  for (const proc of processes) {
    const exec = proc.pm2_env?.pm_exec_path;
    if (!proc.name || !exec) continue;
    const execDir = normalizeDir(path.dirname(exec));
    if (execDir === target || execDir === normalizeDir(path.join(dir, "dist"))) return proc.name;
  }
  return null;
}

export function parseCommitCount(value: string | number | undefined): number {
  const n = typeof value === "number" ? value : Number.parseInt(value ?? "1", 10);
  if (!Number.isInteger(n) || n < 1 || n > 100) throw new Error("--commits must be a whole number between 1 and 100");
  return n;
}

// ==================== Shell helpers ====================

async function commandWorks(cmd: string, args: string[], cwd?: string): Promise<boolean> {
  try {
    await execa(cmd, args, { cwd });
    return true;
  } catch {
    return false;
  }
}

function requirePm2(): Promise<void> {
  return commandWorks("pm2", ["--version"]).then((ok) => {
    if (!ok) {
      error("PM2 is not installed globally.");
      info("Install it with: npm install -g pm2");
      process.exit(1);
    }
  });
}

async function requireGitRepo(dir: string): Promise<void> {
  if (!(await commandWorks("git", ["rev-parse", "--git-dir"], dir))) {
    error("Not a git repository. Run this from the deployed app's folder (or use: katax deploy init).");
    process.exit(1);
  }
}

function reportUnlessShown(err: unknown): void {
  if (err && typeof err === "object" && "reported" in err) return;
  error(err instanceof Error ? err.message : String(err));
}

async function step(label: string, done: string, fn: () => Promise<unknown>): Promise<void> {
  const spinner = ora(label).start();
  try {
    await fn();
    spinner.succeed(done);
  } catch (err) {
    spinner.fail(`${label.replace(/\.\.\.$/, "")} failed`);
    const e = err as { stderr?: string; message?: string };
    console.error(chalk.red((e.stderr || e.message || String(err)).trim()));
    throw Object.assign(err as object, { reported: true });
  }
}

async function installAndBuild(dir: string): Promise<void> {
  const pm = detectPackageManager(dir);
  if (pm !== "npm" && !(await commandWorks(pm, ["--version"]))) {
    throw new Error(`This repo uses ${pm} (lockfile) but ${pm} is not installed. Run: corepack enable  (or npm i -g ${pm})`);
  }
  await step(`Installing dependencies (${pm})...`, "Dependencies installed", () =>
    execa(pm, installArgs(pm, dir), { cwd: dir }),
  );
  await step("Building...", "Built", () => execa(pm, ["run", "build"], { cwd: dir }));
}

async function readJson(file: string): Promise<Record<string, unknown> | null> {
  try {
    return JSON.parse(fs.readFileSync(file, "utf-8"));
  } catch {
    return null;
  }
}

/** --app-name, then .katax-deploy.json, then the PM2 app running from this folder, then the folder name. */
async function resolveAppName(dir: string, explicit?: string): Promise<string> {
  if (explicit) return explicit;

  const config = await readJson(path.join(dir, CONFIG_FILE));
  if (typeof config?.appName === "string" && config.appName) {
    gray(`  App from ${CONFIG_FILE}: ${config.appName}`);
    return config.appName;
  }

  try {
    const { stdout } = await execa("pm2", ["jlist"]);
    const found = findPm2AppForDir(JSON.parse(stdout), dir);
    if (found) {
      gray(`  App found in PM2 for this folder: ${found}`);
      await saveDeployConfig(dir, { appName: found });
      return found;
    }
  } catch {
    // fall through
  }

  const fallback = path.basename(dir);
  warning(`Using the folder name as PM2 app name: ${fallback} (check with: pm2 list, or pass --app-name)`);
  return fallback;
}

async function saveDeployConfig(dir: string, data: Record<string, unknown>): Promise<void> {
  const file = path.join(dir, CONFIG_FILE);
  const previous = (await readJson(file)) ?? {};
  try {
    await writeFile(file, JSON.stringify({ ...previous, ...data, updatedAt: new Date().toISOString() }, null, 2) + "\n");
  } catch (err) {
    warning(`Could not save ${CONFIG_FILE}: ${err instanceof Error ? err.message : String(err)}`);
  }
}

async function gitHead(dir: string): Promise<string> {
  return (await execa("git", ["rev-parse", "HEAD"], { cwd: dir })).stdout.trim();
}

/** SQL migrations added/changed between two commits (they are never applied automatically). */
async function changedMigrations(dir: string, from: string, to: string): Promise<string[]> {
  if (from === to) return [];
  try {
    const { stdout } = await execa("git", ["diff", "--name-only", "--diff-filter=AM", from, to, "--", "migrations"], {
      cwd: dir,
    });
    return stdout.split("\n").map((l) => l.trim()).filter((l) => l.endsWith(".sql"));
  } catch {
    return [];
  }
}

function warnMigrations(files: string[], heading: string): void {
  if (files.length === 0) return;
  console.log();
  warning(heading);
  for (const f of files) gray(`  ${f}`);
  gray(`  Apply them in order, e.g.: psql "$DATABASE_URL" -f <file>  (or with DB_HOST/DB_USER/DB_NAME from .env)`);
}

async function confirmOrExit(yes: boolean | undefined, message: string, defaultValue: boolean): Promise<boolean> {
  if (yes) return true;
  if (!process.stdin.isTTY) {
    error(`${message} — no terminal to ask. Pass -y/--yes to run without confirmation.`);
    process.exit(1);
  }
  const { ok } = await inquirer.prompt<{ ok: boolean }>([
    { type: "confirm", name: "ok", message, default: defaultValue },
  ]);
  return ok;
}

/** pm2 reload: zero-downtime in cluster mode, graceful restart in fork mode; reloads env from the ecosystem. */
async function reloadApp(appName: string): Promise<void> {
  await step(`Reloading ${appName} in PM2...`, `${appName} reloaded`, () =>
    execa("pm2", ["reload", appName, "--update-env"]),
  );
}

// ==================== deploy init ====================

export async function deployInitCommand(): Promise<void> {
  title("🚀 Katax Deploy - Initial Setup");
  await requirePm2();

  const base = await inquirer.prompt<{ repoUrl: string; branch: string; installPath: string }>([
    {
      type: "input",
      name: "repoUrl",
      message: "Git repository URL (https:// or git@...):",
      validate: (input: string) =>
        isValidGitRepoUrl(input) || "Use a Git URL: https://..., ssh://... or git@host:owner/repo.git",
    },
    { type: "input", name: "branch", message: "Branch to deploy:", default: "main" },
    {
      type: "input",
      name: "installPath",
      message: "Parent folder (absolute):",
      default: `/home/${process.env.USER || "ubuntu"}/apps`,
      validate: (input: string) => path.isAbsolute(input) || "Use an absolute path",
    },
  ]);

  const repoName = path.basename(base.repoUrl.trim().replace(/\.git$/, "").replace(/[:/]+$/, "")).replace(/[^a-z0-9-_]/gi, "-");
  const { folder } = await inquirer.prompt<{ folder: string }>([
    {
      type: "input",
      name: "folder",
      message: "Folder name for the app:",
      default: repoName || "my-api",
      validate: (input: string) => NAME_PATTERN.test(input) || "Letters, numbers, hyphens and underscores only",
    },
  ]);

  const dir = path.join(base.installPath, folder);
  if (fs.existsSync(dir)) {
    error(`${dir} already exists. Use "katax deploy update" inside it, or choose another folder.`);
    process.exit(1);
  }

  try {
    await step("Cloning repository...", "Repository cloned", () =>
      execa("git", ["clone", "--branch", base.branch, "--", base.repoUrl.trim(), dir]),
    );

    // PM2 config: the repo's own ecosystem.config.cjs wins (katax init creates one: fork, 1 instance).
    const ecosystemPath = path.join(dir, ECOSYSTEM_FILE);
    let appName: string;
    if (fs.existsSync(ecosystemPath)) {
      const declared = readEcosystemAppName(fs.readFileSync(ecosystemPath, "utf-8"));
      if (!declared) throw new Error(`${ECOSYSTEM_FILE} has no app "name"; add one and push it.`);
      appName = declared;
      info(`Using the repo's ${ECOSYSTEM_FILE} (PM2 app "${appName}"). Change instances/name there and push.`);
    } else {
      const pm2 = await inquirer.prompt<{ appName: string; instances: number; maxMemory: string }>([
        {
          type: "input",
          name: "appName",
          message: "PM2 app name:",
          default: folder,
          validate: (input: string) => NAME_PATTERN.test(input) || "Letters, numbers, hyphens and underscores only",
        },
        {
          type: "list",
          name: "instances",
          message: "Instances:",
          choices: [
            { name: "1, fork mode (recommended: in-memory rate limits, Socket.IO and cron need it)", value: 1 },
            { name: "2, cluster mode (needs Redis-backed rate limits/Socket.IO adapter)", value: 2 },
            { name: "4, cluster mode (needs Redis-backed rate limits/Socket.IO adapter)", value: 4 },
          ],
          default: 0,
        },
        { type: "input", name: "maxMemory", message: "Restart above (e.g. 512M, 1G):", default: "512M" },
      ]);
      appName = pm2.appName;
      // Untracked file: it doesn't make the working tree dirty for later `git pull`s.
      await writeFile(ecosystemPath, renderDeployEcosystem(appName, pm2.instances, pm2.maxMemory));
      success(`${ECOSYSTEM_FILE} created (commit it to the repo to keep it versioned)`);
    }

    const running = await commandWorks("pm2", ["describe", appName]);
    if (running) throw new Error(`PM2 already has an app named "${appName}". Rename it in ${ECOSYSTEM_FILE} or delete it first.`);

    await setupEnvFile(dir);
    await installAndBuild(dir);

    fs.mkdirSync(path.join(dir, "logs"), { recursive: true });
    await step("Starting with PM2...", "Started with PM2", async () => {
      await execa("pm2", ["start", ECOSYSTEM_FILE, "--env", "production"], { cwd: dir });
      await execa("pm2", ["save"]);
    });

    await saveDeployConfig(dir, { appName, branch: base.branch });

    const migrationsDir = path.join(dir, "migrations");
    const migrations = fs.existsSync(migrationsDir)
      ? fs.readdirSync(migrationsDir).filter((f) => f.endsWith(".sql")).sort().map((f) => `migrations/${f}`)
      : [];
    warnMigrations(migrations, "This repo has SQL migrations. katax deploy does not run them:");

    console.log();
    success("Deployed");
    info(`📍 ${dir}`);
    info(`🔧 PM2 app: ${appName}`);
    gray(`\n  katax deploy update        # pull, install, build, reload (run inside ${dir})`);
    gray(`  katax deploy logs -f       # follow logs`);
    gray(`  pm2 startup                # once per server: start PM2 apps on boot\n`);
  } catch (err) {
    reportUnlessShown(err);
    console.log();
    error(`Deployment stopped. Fix the error above; the clone stays in ${dir} (delete it to retry from scratch).`);
    process.exit(1);
  }
}

/** .env is gitignored, so a fresh clone has none: offer to build it from .env.example. */
async function setupEnvFile(dir: string): Promise<void> {
  const envPath = path.join(dir, ".env");
  const examplePath = path.join(dir, ".env.example");
  if (fs.existsSync(envPath)) return;
  if (!fs.existsSync(examplePath)) {
    warning("No .env or .env.example in the repo: set the variables in ecosystem.config.cjs or create .env by hand.");
    return;
  }

  const entries = parseEnvFile(fs.readFileSync(examplePath, "utf-8"));
  const { mode } = await inquirer.prompt<{ mode: "fill" | "copy" | "skip" }>([
    {
      type: "list",
      name: "mode",
      message: `The repo has .env.example (${entries.length} variables). Create .env now?`,
      choices: [
        { name: "Yes, ask me each value (secrets generated, NODE_ENV=production)", value: "fill" },
        { name: "Copy it as is (edit .env later, then: pm2 reload <app>)", value: "copy" },
        { name: "No", value: "skip" },
      ],
    },
  ]);
  if (mode === "skip") {
    warning("No .env created: the app may fail to start until you create it.");
    return;
  }

  const values: EnvEntry[] = [];
  for (const entry of entries) {
    const fallback = productionDefault(entry);
    if (mode === "copy") {
      values.push({ key: entry.key, value: fallback });
      continue;
    }
    const secret = isSecretKey(entry.key);
    const generated = fallback !== entry.value;
    const { value } = await inquirer.prompt<{ value: string }>([
      {
        type: secret ? "password" : "input",
        name: "value",
        mask: "*",
        message: secret && generated ? `${entry.key} (Enter = random secret):` : `${entry.key}:`,
        ...(secret ? {} : { default: fallback }),
      },
    ]);
    values.push({ key: entry.key, value: value === "" && secret ? fallback : value });
  }
  fs.writeFileSync(envPath, renderEnvFile(values), { mode: 0o600 });
  success(".env created (permissions 600)");
}

// ==================== deploy update ====================

export async function deployUpdateCommand(options: {
  branch?: string;
  hard?: boolean;
  appName?: string;
  yes?: boolean;
}): Promise<void> {
  title("🔄 Katax Deploy - Update");
  const dir = process.cwd();
  await requireGitRepo(dir);
  await requirePm2();

  const appName = await resolveAppName(dir, options.appName);
  const branch = options.branch || (await execa("git", ["branch", "--show-current"], { cwd: dir })).stdout.trim();
  if (!branch) {
    error("Detached HEAD (after a rollback?). Pass the branch: katax deploy update -b main");
    process.exit(1);
  }

  info(`📦 App: ${chalk.cyan(appName)}   🌿 Branch: ${chalk.cyan(branch)}`);
  if (options.hard) warning("--hard: local changes to tracked files will be discarded.");
  if (!(await confirmOrExit(options.yes, "Proceed with update?", true))) {
    warning("Update cancelled");
    return;
  }

  try {
    const before = await gitHead(dir);
    await step("Updating code from git...", "Code updated", async () => {
      await execa("git", ["fetch", "origin", branch], { cwd: dir });
      if (options.hard) {
        await execa("git", ["checkout", branch], { cwd: dir });
        await execa("git", ["reset", "--hard", `origin/${branch}`], { cwd: dir });
      } else {
        await execa("git", ["checkout", branch], { cwd: dir });
        await execa("git", ["merge", "--ff-only", `origin/${branch}`], { cwd: dir });
      }
    });
    const after = await gitHead(dir);
    if (before === after) gray("  Already up to date; rebuilding anyway.");
    else gray(`  ${before.slice(0, 7)} → ${after.slice(0, 7)}`);

    await installAndBuild(dir);
    await reloadApp(appName);
    await saveDeployConfig(dir, { appName, branch });
    warnMigrations(await changedMigrations(dir, before, after), "New or changed SQL migrations (not applied):");
    console.log();
    success("Updated");
    gray(`  Logs: katax deploy logs -f\n`);
  } catch (err) {
    reportUnlessShown(err);
    console.log();
    error("Update stopped. The app keeps running the previous build until a successful reload.");
    if (!options.hard) gray("  If git refused because of local changes on the server: katax deploy update --hard");
    process.exit(1);
  }
}

// ==================== deploy rollback ====================

export async function deployRollbackCommand(options: {
  commits?: string;
  appName?: string;
  yes?: boolean;
}): Promise<void> {
  title("⏮️  Katax Deploy - Rollback");
  const dir = process.cwd();
  await requireGitRepo(dir);
  await requirePm2();

  let commits: number;
  try {
    commits = parseCommitCount(options.commits);
  } catch (err) {
    error(err instanceof Error ? err.message : String(err));
    process.exit(1);
  }
  const appName = await resolveAppName(dir, options.appName);
  const target = (await execa("git", ["log", "-1", "--format=%h %s", `HEAD~${commits}`], { cwd: dir }).catch(() => null))
    ?.stdout;
  if (!target) {
    error(`There are fewer than ${commits + 1} commits in this checkout.`);
    process.exit(1);
  }

  warning(`Rolling ${appName} back ${commits} commit(s) to: ${target}`);
  gray("  Database migrations are not reverted.");
  if (!(await confirmOrExit(options.yes, "Continue?", false))) {
    warning("Rollback cancelled");
    return;
  }

  try {
    await step("Resetting code...", "Code rolled back", () => execa("git", ["reset", "--hard", `HEAD~${commits}`], { cwd: dir }));
    await installAndBuild(dir);
    await reloadApp(appName);
    console.log();
    success("Rolled back");
    gray("  The next `katax deploy update` brings the branch forward again.\n");
  } catch (err) {
    reportUnlessShown(err);
    console.log();
    error("Rollback stopped.");
    process.exit(1);
  }
}

// ==================== deploy logs / status ====================

export async function deployLogsCommand(options: { lines?: string; follow?: boolean; appName?: string }): Promise<void> {
  const appName = await resolveAppName(process.cwd(), options.appName);
  title(`📋 PM2 Logs - ${appName}`);
  const args = ["logs", appName, "--lines", String(Number.parseInt(options.lines ?? "", 10) || 50)];
  if (!options.follow) args.push("--nostream");
  try {
    await execa("pm2", args, { stdio: "inherit" });
  } catch {
    error(`Could not read logs for "${appName}" (check the name with: pm2 list)`);
    process.exit(1);
  }
}

export async function deployStatusCommand(): Promise<void> {
  title("📊 PM2 Status");
  try {
    await execa("pm2", ["list"], { stdio: "inherit" });
  } catch {
    error("Could not run pm2 list (is PM2 installed?)");
    process.exit(1);
  }
}
